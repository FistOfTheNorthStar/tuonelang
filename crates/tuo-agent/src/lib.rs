//! Agent protocol surface for tuonelang.
//!
//! First-class agentic workflows are a core tuonelang goal. This crate will expose
//! machine-readable compiler feedback to coding agents, reusing the shared
//! semantic engine ([`tuo_db`], [`tuo_compiler`]) rather than reimplementing
//! it.
//!
//! No agent protocol is implemented yet; only the crate boundary is
//! established.
